import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {mkdtemp, mkdir, readFile, writeFile, symlink, rm, stat} from 'node:fs/promises';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
import {tmpdir} from 'node:os';
import {createBackup, verifyBackup, restoreBackup} from '../scripts/backup.ts';
const root=await mkdtemp(join(tmpdir(),'jotstead-backup-hardened-'));
const source=join(root,'live'),out=join(root,'backup'),restored=join(root,'restored');
try {
  await mkdir(join(source,'uploads'),{recursive:true});
  const db=new DatabaseSync(join(source,'workspace.sqlite'));
  db.exec('CREATE TABLE workspace (id INTEGER PRIMARY KEY, revision INTEGER NOT NULL, body TEXT NOT NULL);CREATE TABLE history (id INTEGER PRIMARY KEY,page_id TEXT,revision INTEGER,body TEXT,created_at TEXT); INSERT INTO workspace VALUES(1, 3, \'{"name":"My private notes"}\'); INSERT INTO history VALUES(1,\'home\',2,\'{"title":"Before"}\',\'now\');');
  db.close();
  const bytes=Buffer.from([0, 255, 1, 2, 3, 42]);
  await writeFile(join(source,'uploads','a-file'),bytes);
  await writeFile(join(source,'uploads','a-file.json'),JSON.stringify({name:'attachment',size:6}));
  const m=await createBackup(source,out);
  assert.equal(m.revision,3); assert.equal(m.files.length,3);
  assert.equal((await verifyBackup(out)).files.length,3);
  const cli=spawnSync(process.execPath,['--experimental-strip-types','scripts/backup.ts','--verify',out],{encoding:'utf8',cwd:process.cwd()});
  assert.equal(cli.status,0,cli.stderr);
  assert.match(cli.stdout,/Verified 3 backup files/);
  await restoreBackup(out,restored,true);
  const dry=spawnSync(process.execPath,['--experimental-strip-types','scripts/backup.ts','--restore',out,restored,'--dry-run'],{encoding:'utf8',cwd:process.cwd()});
  assert.equal(dry.status,0,dry.stderr);
  await assert.rejects(stat(restored), /ENOENT/);
  await restoreBackup(out,restored);
  assert.deepEqual(await readFile(join(restored,'uploads','a-file')),bytes);
  const check=new DatabaseSync(join(restored,'workspace.sqlite'));
  assert.equal(check.prepare('SELECT revision FROM workspace WHERE id=1').get().revision,3);
  assert.equal(check.prepare('SELECT COUNT(*) AS n FROM history').get().n,1);
  check.close();
  await assert.rejects(restoreBackup(out,restored),/already exists/);
  await assert.rejects(restoreBackup(out,restored,true),/already exists/);
  await assert.rejects(createBackup(source,join(source,'backups','unsafe')),/outside/);
  await symlink(join(source,'uploads'),join(root,'uploads-alias'));
  await assert.rejects(createBackup(source,join(root,'uploads-alias','bad-backup')),/inside the live data directory/);
  await symlink(join(out,'uploads'),join(root,'backup-alias'));
  await assert.rejects(restoreBackup(out,join(root,'backup-alias','bad-restore')),/inside the backup directory/);
  await writeFile(join(out,'uploads','a-file'),Buffer.from('corrupted'));
  await assert.rejects(verifyBackup(out),/checksum mismatch/);
  await assert.rejects(restoreBackup(out,join(root,'bad-restore')),/checksum mismatch/);
  await symlink(join(source,'uploads','a-file'),join(source,'uploads','attack-file'));
  await assert.rejects(createBackup(source,join(root,'unsafe')),/Not a regular file/);
  console.log('PASS: snapshot/revision/history, bytes, manifest, dry run, safe restore, tamper detection, traversal, symlink rejection');
} finally { await rm(root,{recursive:true,force:true}); }
